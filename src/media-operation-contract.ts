import * as z from "zod";
import type {
  MediaOperationOwner,
  MediaOperationCoordinates,
  MediaOperationRequest,
} from "./media-operation-owner.js";
import type { MediaUnits } from "./gateway-models.js";
import type { MediaReferenceBytes } from "./index.js";

/**
 * The host's billing owner for Media. Every call is keyed by the durable
 * operation id and must be idempotent: a lost acknowledgement is retried with
 * the same id and must never admit, hold, or charge twice.
 */
export type MediaMetering = Readonly<{
  /**
   * Admit one generation and hold its price before any provider dispatch.
   * Throws {@link MediaBillingRefusal} for a definitive refusal. Returns the
   * customer price in milliunits (1 cent = 1,000 milliunits).
   */
  admit: (
    input: Readonly<{
      /** Durable operation name. */
      operationId: string;
      /** Provider catalog model identifier. */
      model: string;
      /** Billing unit and count: one image, or seconds of video. */
      unit: MediaUnits["unit"];
      /** Number of admitted or delivered units. */
      units: number;
      /** Provider cost of all units together. */
      providerCostMilliunits: number;
    }>,
  ) => Promise<
    Readonly<{
      /** Host-admitted customer price. */
      priceMilliunits: number;
    }>
  >;
  /** Settle delivered units: all admitted units once saved, 0 when nothing was delivered. */
  settle: (
    input: Readonly<{
      /** Durable operation name. */
      operationId: string;
      /** Number of admitted or delivered units. */
      units: number;
    }>,
  ) => Promise<void>;
}>;

/** Local or RPC methods consumed by a replay-safe generation. */
export type MediaOperation = {
  [
    Method in
      | "admit"
      | "claim"
      | "dispatchInBackground"
      | "interruptGeneration"
      | "readGenerated"
      | "recordEstimate"
      | "recordGenerated"
      | "recordSucceeded"
      | "recordWritten"
      | "recordWrittenWithoutSettlement"
      | "releaseEstimate"
      | "releaseWrite"
  ]: (
    ...input: Parameters<MediaOperationOwner[Method]>
  ) =>
    | ReturnType<MediaOperationOwner[Method]>
    | Promise<Awaited<ReturnType<MediaOperationOwner[Method]>>>;
};

/** Admitted identity, durable operation and host effects for one generation. */
export type MediaExecution = Readonly<{
  /** Durable owner methods for this generation. */
  operation: MediaOperation;
  /** Host-admitted actor identifier. */
  actorUserId: string;
  /** Host namespace and owner identity. */
  coordinates: MediaOperationCoordinates;
  /** Stable caller request identity reused on retries. */
  requestId: string;
  /** Captured generation and fixed destination. */
  request: MediaOperationRequest;
  /** The billing owner, or `unmetered` when the host pays its own provider. */
  metering: MediaMetering | "unmetered";
  /** Optional cancellation signal. */
  signal?: AbortSignal;
  /** Host-owned destination authorization and writing. */
  destination: Readonly<{
    /** Check host permission before writing or dispatching generation. */
    authorize: () => Promise<void>;
    /** Save exact generated bytes to the admitted destination. */
    write: (bytes: Uint8Array) => Promise<void>;
  }>;
  /** Reference preparation and provider dispatch effects. */
  generation: Readonly<{
    /** Resolve references and price before provider dispatch. */
    prepare: () => Promise<
      Readonly<{
        /** Estimated provider cost in milliunits, where 1 cent is 1,000 milliunits. */
        costMilliunits: number;
        /** Host-authorized reference images. */
        references: readonly MediaReferenceBytes[];
        /** Dispatch one provider call with the prepared inputs. */
        run: (signal?: AbortSignal) => Promise<
          Readonly<{
            /** Generated output bytes. */
            bytes: Uint8Array;
            /** Actual output encoding. */
            format: string;
          }>
        >;
      }>
    >;
  }>;
}>;

/** Decode a completed generation, destination path and estimated or settled price. */
export const mediaResultSchema = z.strictObject({
  /** Output byte length. */
  bytes: z.number().int().positive(),
  /** Admitted price in milliunits, where 1 cent is 1,000 milliunits. */
  costMilliunits: z.number().int().nonnegative(),
  /** Fixed destination or reference file path. */
  path: z.string().min(1).max(1_024),
  /** Actual output encoding. */
  format: z.enum({
    /** PNG image encoding. */
    png: "png",
    /** JPEG image encoding. */
    jpeg: "jpeg",
    /** GIF image encoding. */
    gif: "gif",
    /** WebP image encoding. */
    webp: "webp",
    /** MP4 video encoding. */
    mp4: "mp4",
  }),
  /** Requested image height or nominal video selector, not decoded MP4 dimensions. */
  height: z.number().int().positive(),
  /** Provider catalog model identifier. */
  model: z.string().min(1).max(256),
  /** Requested image width or nominal video selector, not decoded MP4 dimensions. */
  width: z.number().int().positive(),
});
