/** Identity supplied by the admitting host, never selected by a request body. */
export type MediaScope = Readonly<{
  /** Host-admitted actor identity. */
  actorId: string;
  /** Host-owned isolation namespace. */
  namespace: string;
  /** Host-owned application or actor within the namespace. */
  owner: string;
  /** Host-admitted destination identity. */
  destinationId: string;
}>;

/** Customer-visible refusal text owned by a metered host. */
export type MediaRefusalMessages = Readonly<
  Record<MediaBillingRefusalCode, string>
>;

/** Host authority, durable operations, provider, metering and destination access. */
export type MediaServiceHost = Readonly<{
  /** Identity admitted by the host before service construction. */
  scope: MediaScope;
  /** Resolve durable operations by their service-selected name. */
  operations: {
    /** Resolve the service-selected operation name to its local or RPC owner. */
    getByName(name: string): MediaExecution["operation"];
  };
  /** The provider call for every generation (Workers AI, or the Hub's edge on celld). */
  provider: MediaProvider;
  /** Host-owned address roster, committed before the operation can create storage. */
  beforeAdmit?: ((requestId: string) => Promise<void>) | undefined;
  /** Recheck the host's generation authority only before a new dispatch.
   * Retained output still uses destination authorization when saving. */
  authorizeGeneration?: () => Promise<void>;
  /** Authorize and save generated bytes, and optionally read references. */
  destination: Readonly<{
    /** Check host permission before writing or dispatching generation. */
    authorize: (path: string) => Promise<void>;
    /** Save exact generated bytes to the admitted destination. */
    write: (path: string, bytes: Uint8Array) => Promise<void>;
    /** Authorize and fit one selected reference image for the catalog model. */
    readReference?: (
      reference: MediaReference,
      model: string,
    ) => Promise<MediaReferenceBytes>;
  }>;
  /** Translate host authority failures; undefined uses the shared Media failure. */
  onFailure?: (error: MediaExecutionError) => Response | undefined;
}> &
  (
    | Readonly<{
        /** The host pays its own provider directly. */
        metering: "unmetered";
        /** Unmetered hosts do not have billing refusal policy. */
        refusalMessages?: never;
      }>
    | Readonly<{
        /** Idempotent admission and settlement owned by the host. */
        metering: MediaMetering;
        /** Customer copy for each definitive billing refusal. */
        refusalMessages: MediaRefusalMessages;
      }>
  );

const headers = {
  "Cache-Control": "private, no-store",
  "X-Content-Type-Options": "nosniff",
};

function failure(
  error: MediaExecutionError | MediaSettingsError,
  refusalMessages?: Readonly<Record<MediaBillingRefusalCode, string>>,
): Response {
  if (error instanceof MediaSafetyFilterRefusal)
    return Response.json(
      {
        error: describeAppError(
          new AppError(error.message, {
            code: "SAFETY_FILTER_REFUSED",
            retryable: false,
          }),
        ).message,
        stage: "provider",
        code: "SAFETY_FILTER_REFUSED",
        retryable: false,
        provider: error.provider,
      },
      { status: 400, headers },
    );
  if (
    error instanceof MediaExecutionError &&
    error.cause instanceof MediaOutputFormatMismatch
  )
    return Response.json(
      {
        error:
          "Media provider did not return the requested image format; nothing was saved. Start a new request.",
        stage: error.stage,
        code: "HOST_FAILURE",
        retryable: false,
      },
      {
        status: 503,
        headers,
      },
    );
  if (
    error instanceof MediaExecutionError &&
    error.stage === "billing" &&
    error.cause instanceof MediaBillingRefusal
  )
    return Response.json(
      {
        error:
          refusalMessages?.[error.cause.code] ??
          "Media generation was refused by the host.",
        stage: "billing",
        code:
          error.cause.code === "insufficient_credits"
            ? "INSUFFICIENT_CREDIT"
            : "CAPABILITY_DENIED",
        retryable: false,
      },
      {
        status: error.cause.code === "denied" ? 403 : 402,
        headers,
      },
    );
  if (
    error instanceof MediaSettingsError ||
    (error.stage === "estimate" && error.cause instanceof MediaSettingsError)
  )
    return Response.json(
      {
        error:
          "Media generation settings are invalid; check the model, dimensions, steps, and destination.",
        stage: "settings",
        code: "INVALID_ARGUMENT",
        retryable: false,
      },
      {
        status: 400,
        headers,
      },
    );
  if (error.stage === "provider") {
    const code =
      error.customerCharge === "none"
        ? "MEDIA_PROVIDER_FAILURE_UNCHARGED"
        : "MEDIA_PROVIDER_FAILURE";
    return Response.json(
      {
        error: describeAppError(
          new AppError(error.message, {
            code,
            retryable: false,
          }),
        ).message,
        stage: error.stage,
        code,
        retryable: false,
        provider: error.provider,
      },
      { status: 503, headers },
    );
  }
  const messages = {
    "generation-authorization":
      "Media generation permission could not be checked; try again.",
    "destination-authorization":
      "Media destination permission could not be checked; try again.",
    "destination-write":
      "Media generated an image but could not save it; retry this request to save the retained result.",
    estimate:
      "Media could not prepare the image inputs or estimate their cost; check the reference files and retry.",
    billing: "Media billing is unavailable; retry this request.",
    normalization:
      "Media provider returned an unusable image; start a new request only after checking provider status.",
    artifact:
      "Media generated output could not be retained or read; try again.",
    operation: "Media operation is unresolved; try again.",
  };
  return Response.json(
    {
      error: messages[error.stage],
      stage: error.stage,
      code: "HOST_FAILURE",
      retryable: error.stage !== "normalization",
      provider:
        error instanceof MediaExecutionError ? error.provider : undefined,
    },
    {
      status: 503,
      headers,
    },
  );
}

/** One Media generation request, already carrying its idempotency key. */
export type MediaGenerationRequest = Readonly<{
  /** Stable request identity reused for retries. */
  requestId: string;
  /** Fixed destination path for this operation. */
  path: string;
  /** Model settings validated before admission. */
  settings: Parameters<typeof validateMediaGenerationSettings>[0];
  /** Optional verified image format pin. */
  outputFormat?: z.output<typeof mediaRequestSchema>["outputFormat"];
}>;

/** The typed result of one generation, shared by the Hono route and the Agent path. */
export type MediaGenerationOutcome =
  | Readonly<{
      /** Outcome or model-kind discriminant. */
      kind: "succeeded";
      /** Fixed destination or reference file path. */
      path: string;
      /** Output byte length. */
      bytes: number;
      /** Admitted price in milliunits, where 1 cent is 1,000 milliunits. */
      costMilliunits: number;
      /** Actual output encoding. */
      format: "png" | "jpeg" | "gif" | "webp" | "mp4";
      /** Requested image height or nominal video selector, not decoded MP4 dimensions. */
      height: number;
      /** Provider catalog model identifier. */
      model: string;
      /** Requested image width or nominal video selector, not decoded MP4 dimensions. */
      width: number;
    }>
  | Readonly<{
      /** Outcome or model-kind discriminant. */
      kind: "pending";
      /** Whether generation is running through the durable alarm. */
      background: boolean;
      /** Delay before retrying the same request, in seconds. */
      retryAfterSeconds: number;
    }>
  | Readonly<{
      /** Outcome or model-kind discriminant. */
      kind: "conflict";
    }>
  | Readonly<{
      /** Outcome or model-kind discriminant. */
      kind: "interrupted";
    }>
  | Readonly<{
      /** Outcome or model-kind discriminant. */
      kind: "unavailable";
    }>;

/** Generate through the Effect core with a Promise boundary preserving typed domain failures. */
export async function generateMedia(
  host: MediaServiceHost,
  request: MediaGenerationRequest,
  signal?: AbortSignal,
): Promise<MediaGenerationOutcome> {
  const result = await Effect.runPromise(
    Effect.result(runMediaGeneration(host, request, signal)),
  );
  return Result.getOrThrowWith(result, (error) => error);
}

function outcomeResponse(outcome: MediaGenerationOutcome): Response {
  if (outcome.kind === "conflict")
    return Response.json(
      {
        error: "This request ID already belongs to a different Media request.",
        stage: "operation",
        code: "INVALID_ARGUMENT",
        retryable: false,
      },
      {
        status: 409,
        headers,
      },
    );
  if (outcome.kind === "pending" && outcome.background)
    // A video generation runs in the background; retry this request id.
    return Response.json(
      mediaPendingSchema.parse({
        status: "pending",
        retryAfterSeconds: outcome.retryAfterSeconds,
      }),
      {
        status: 202,
        headers: {
          ...headers,
          "Retry-After": String(outcome.retryAfterSeconds),
        },
      },
    );
  if (outcome.kind === "pending")
    return Response.json(
      {
        error:
          "Media generation is still in progress; retry this request to check its durable result.",
        stage: "operation",
        code: "HOST_FAILURE",
        retryable: true,
      },
      {
        status: 409,
        headers,
      },
    );
  if (outcome.kind === "interrupted" || outcome.kind === "unavailable")
    return Response.json(
      {
        error:
          "Media generation was interrupted before completion; start a new request.",
        stage: "operation",
        code: "HOST_FAILURE",
        retryable: false,
      },
      {
        status: 503,
        headers,
      },
    );
  return Response.json(
    mediaResultSchema.parse({
      bytes: outcome.bytes,
      costMilliunits: outcome.costMilliunits,
      path: outcome.path,
      format: outcome.format,
      height: outcome.height,
      model: outcome.model,
      width: outcome.width,
    }),
    { headers },
  );
}

/** Relative HTTP routes; the caller admits identity and supplies destination access. */
export function createMediaService(host: MediaServiceHost) {
  const app = new Hono();
  app.get("/models", () =>
    Response.json(
      listMediaModels().map((model) =>
        host.destination.readReference !== undefined ||
        model.input.maxReferences === 0
          ? model
          : {
              ...model,
              label: `${model.label} (reference images unavailable in this App host)`,
              input: {
                ...model.input,
                maxReferences: 0,
                referenceField: null,
              },
            },
      ),
      { headers },
    ),
  );
  app.post("/generate", async (context) => {
    const body = await readJsonBody(context.req.raw);
    const input =
      body.kind === "parsed"
        ? mediaRequestSchema.safeParse(body.value)
        : undefined;
    const requestId = identifier.safeParse(context.req.header("X-Request-Id"));
    if (input?.success !== true || !requestId.success)
      return failure(new MediaSettingsError("invalid request"));
    return Effect.runPromise(
      runMediaGeneration(
        host,
        {
          requestId: requestId.data,
          path: input.data.path,
          settings: input.data.settings,
          outputFormat: input.data.outputFormat,
        },
        context.req.raw.signal,
      ).pipe(
        Effect.match({
          onSuccess: outcomeResponse,
          onFailure: (error) =>
            (error instanceof MediaExecutionError
              ? host.onFailure?.(error)
              : undefined) ?? failure(error, host.refusalMessages),
        }),
      ),
    );
  });
  return app;
}
