async function readJsonBody(request: Request): Promise<
  | Readonly<{
      /** Outcome or model-kind discriminant. */
      kind: "parsed";
      value: unknown;
    }>
  | Readonly<{
      /** Outcome or model-kind discriminant. */
      kind: "invalid";
    }>
> {
  try {
    const value: unknown = await request.json();
    return {
      kind: "parsed",
      value,
    };
  } catch {
    return {
      kind: "invalid",
    };
  }
}

